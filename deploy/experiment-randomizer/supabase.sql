create table if not exists public.experiment_assignments (
  id bigint generated by default as identity primary key,
  participant_id text not null unique,
  browser_token text not null unique,
  condition_code text not null check (condition_code in ('C1','C2','C3','C4','C5','C6')),
  assigned_at timestamptz not null default now()
);

create index if not exists experiment_assignments_condition_idx
  on public.experiment_assignments(condition_code);

-- 동시 접속이 있어도 두 요청이 같은 '최소 인원 조건'을 보고 충돌하지 않도록
-- transaction-level advisory lock으로 배정 절차를 직렬화합니다.
create or replace function public.assign_participant(p_browser_token text)
returns table(participant_id text, condition_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
  existing_id text;
  existing_condition text;
  selected_condition text;
  new_id text;
  next_number bigint;
begin
  -- 같은 브라우저 토큰이면 기존 배정을 그대로 반환합니다.
  select ea.participant_id, ea.condition_code
    into existing_id, existing_condition
  from public.experiment_assignments ea
  where ea.browser_token = p_browser_token;

  if existing_id is not null then
    return query select existing_id, existing_condition;
    return;
  end if;

  -- 배정 순간만 잠급니다. 참가자 1명당 매우 짧게 유지됩니다.
  perform pg_advisory_xact_lock(20260814);

  -- lock 대기 중 같은 토큰이 이미 저장됐을 가능성을 다시 확인합니다.
  select ea.participant_id, ea.condition_code
    into existing_id, existing_condition
  from public.experiment_assignments ea
  where ea.browser_token = p_browser_token;

  if existing_id is not null then
    return query select existing_id, existing_condition;
    return;
  end if;

  -- 현재 배정 수가 가장 적은 조건들만 찾고, 동률이면 그중 무작위 선택합니다.
  with conditions(code) as (
    values ('C1'), ('C2'), ('C3'), ('C4'), ('C5'), ('C6')
  ), counts as (
    select c.code,
           count(ea.id)::bigint as n
    from conditions c
    left join public.experiment_assignments ea
      on ea.condition_code = c.code
    group by c.code
  ), minimum as (
    select min(n) as min_n from counts
  )
  select code into selected_condition
  from counts, minimum
  where counts.n = minimum.min_n
  order by random()
  limit 1;

  -- 사람이 읽기 쉬운 P0001, P0002 ... ID 생성
  select coalesce(max(id), 0) + 1 into next_number
  from public.experiment_assignments;

  new_id := 'P' || lpad(next_number::text, 4, '0');

  insert into public.experiment_assignments(participant_id, browser_token, condition_code)
  values (new_id, p_browser_token, selected_condition);

  return query select new_id, selected_condition;
end;
$$;

-- 함수는 서버의 secret key로만 호출하는 것을 전제로 합니다.
revoke all on function public.assign_participant(text) from public;
revoke all on function public.assign_participant(text) from anon;
revoke all on function public.assign_participant(text) from authenticated;
grant execute on function public.assign_participant(text) to service_role;
